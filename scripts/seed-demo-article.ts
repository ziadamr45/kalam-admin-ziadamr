async function main() {
  const section = await prisma.section.findFirst({
    where: { slug: "al-athar" },
    select: { id: true },
  });

  const article = await prisma.article.upsert({
    where: { slug: SLUG },
    update: { content: CONTENT, contentWithTashkeel: CONTENT_TASHKEEL },
    create: {
      slug: SLUG,
      title: "قالب إرشادي — هكذا تُنسَّق الآيات والأحاديث في مقالاتك",
      summary:
        "قالب مؤقت يوضح ميزة التنسيق القرآني والنبوي الجديدة.\nخط الرسم العثماني للآيات مع التوثيق الآلي.\nخط النسخ الكلاسيكي للأحاديث مع الراوي والتخريج.\nاحذفه أو حرره بعد الاطلاع — لن يُنشر تلقائيًا أبدًا.",
      content: CONTENT,
      contentWithTashkeel: CONTENT_TASHKEEL,
      status: "DRAFT",
      sectionId: section?.id ?? null,
      readingTimeSec: 120,
    },
  });

  console.log(`\n✓ المقال الإرشادي جاهز (مسودة): ${article.slug}`);
  console.log("  → يظهر في لوحة التحكم → المقالات — لا يُنشر تلقائيًا أبدًا.\n");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
